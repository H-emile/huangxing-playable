/**
 * 确定性抖动：同一 (seed, i) 永远返回同一个值，落在 [-amp, +amp]。
 *
 * ⚠️ 绝不能用 Math.random()。两个理由，缺一不可：
 *   ① 地图是"随机种子 + 规则生成"，同种子必须产同结果（便于复现 bug）；
 *   ② 用 Math.random 的话每次重绘值都在变，画面会抖成一片噪点。
 */
export function wobble(seed, i, amp) {
  let h = (Math.imul(seed + 1, 2654435761) + Math.imul(i + 1, 40503)) >>> 0;
  h ^= h >>> 15;
  h = Math.imul(h, 2246822519) >>> 0;
  h ^= h >>> 13;
  // ⚠️ `^=` 会把 h 当成有符号 32 位整数，结果可能是负数；而负数的 `% 2001` 也带负号，
  //    会让取值落到约 [-3*amp, +amp] —— 实测最大 4.488（amp=1.5），破了"幅度不超过 amp"。
  //    补一次 `>>> 0` 拉回无符号，才能保证结果落在 [-amp, +amp]。
  h >>>= 0;
  return ((h % 2001) / 1000 - 1) * amp;
}

/** 把字符串（如 faceId 'left'）转成一个稳定的数字种子 */
export function strSeed(str) {
  let n = 0;
  for (let i = 0; i < str.length; i++) n = (Math.imul(n, 31) + str.charCodeAt(i)) >>> 0;
  return n % 100000;
}

/**
 * 主角轮廓：一个"上宽下窄 + 略前倾 + 左右不对称"的四边形。
 * 返回**相对坐标**（原点在底部中心，向上是负 y），由调用方平移到 (p.x, p.y)。
 * 点的顺序固定：左下 → 右下 → 右上 → 左上。
 * ⚠️ `h` 必须为正数（内部按 -h 使用）；传负数会把图形翻到原点下方，不报错。
 *
 * ⚠️ 为什么只能做到这个程度：主角在屏幕上只有 24×34（占屏高 4.7%），
 *    头身比最多两段，**四肢根本画不出来**（24px 宽里塞四条胳膊，每条 <6px = 一团糊）。
 *    所以荒诞感只能靠"歪、偏、不齐"——这是尺寸决定的，不是偷懒。
 *    用户已明确：**不放大主角**（放大到 36×48 会改变玩家对碰撞距离与挖掘范围的
 *    直觉判断，要重新看手感，不值得）。
 */
export function slouchBox(w, h, lean, topRatio, asym) {
  const wTop = w;                       // 顶宽 = 原宽，保证不比原来更宽（不改变视觉体量）
  const wBot = w / topRatio;            // 底宽收窄 → 上重下轻 = 笨拙
  const halfBotL = (wBot * (1 + asym)) / 2;
  const halfBotR = (wBot * (1 - asym)) / 2;
  const rad = (lean * Math.PI) / 180;
  const cos = Math.cos(rad);
  const sin = Math.sin(rad);
  const rot = (x, y) => ({ x: x * cos - y * sin, y: x * sin + y * cos });
  return [
    rot(-halfBotL, 0),      // 左下
    rot(halfBotR, 0),       // 右下
    rot(wTop / 2, -h),      // 右上
    rot(-wTop / 2, -h),     // 左上
  ];
}